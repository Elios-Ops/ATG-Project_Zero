// RAMPAGE: SAVE LILLY — run the game in the official Project 0 dev kit (Playwright) and capture evidence.
// Serves ../experience read-only. Options:
//   --opts '{"stage":2,"autopilot":true,"invincible":true}'   runs a TEST-ONLY entry generated here (never packaged)
//   --entry main.js (default: the real entry)
//   --shots 2,6,12        seconds after start to capture the game view (device) as PNG
//   --keys '3:Space:100,4:KeyS:300'   at second 3 press Space for 100 ms, ...
//   --hold '5:KeyD:2000'  hold a key (alias of --keys with a long press)
//   --size 960x540  --software (SwiftShader, like the review)  --review (run devkit.review(14) at the end)  --until <s>
// PLAYWRIGHT=<module> node savelilly82/tests/devkit-run.cjs <outdir> [options]
const { chromium } = require(process.env.PLAYWRIGHT || 'playwright');
const http = require('http'), fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..', 'experience');
const args = process.argv.slice(2), OUT = path.resolve(args[0] || 'devkit-out'); fs.mkdirSync(OUT, { recursive: true });
const opt = (k, d) => { const i = args.indexOf('--' + k); return i < 0 ? d : (args[i + 1] && !args[i + 1].startsWith('--') ? args[i + 1] : true); };
const OPTS = opt('opts', null), SCRIPT = opt('script', null), ENTRY = OPTS || SCRIPT ? '__test-entry.js' : opt('entry', 'main.js'), SIZE = opt('size', '960x540'), SOFT = !!opt('software', false), REVIEW = !!opt('review', false), GPU = !!opt('gpu', false);
const SHOTS = String(opt('shots', '3')).split(',').map(Number), UNTIL = +opt('until', Math.max(...SHOTS) + 1), PORT = +opt('port', 5500);
const KEYS = String(opt('keys', '')).split(',').filter(Boolean).map(s => { const [t, code, ms] = s.split(':'); return { t: +t, code, ms: +(ms || 100) }; });
const types = { '.js': 'text/javascript', '.json': 'application/json', '.mp3': 'audio/mpeg', '.png': 'image/png', '.txt': 'text/plain' };
const server = http.createServer((req, res) => {
  res.setHeader('Access-Control-Allow-Origin', '*'); res.setHeader('Cache-Control', 'no-store');
  if (process.env.LOGREQ) console.log('GET', req.url);
  if (SCRIPT && req.url.startsWith('/__test-entry.js')) { res.setHeader('Content-Type', 'text/javascript'); res.end(fs.readFileSync(path.resolve(SCRIPT))); return; }
  if (OPTS && req.url.startsWith('/__test-entry.js')) {
    res.setHeader('Content-Type', 'text/javascript');
    res.end(`// TEST-ONLY entry generated by devkit-run.cjs\nimport { createGame } from './game.js';\nconst O = ${OPTS};\n` +
      `export default async function start(p0) { await createGame(p0, Object.assign({ noHudText: true }, O, { debug: true, test: async api => { if (O.stage !== undefined) api.start(O.stage, O.arcade !== false); } })); }\n`);
    return;
  }
  const f = path.resolve(ROOT, '.' + decodeURIComponent(req.url.split('?')[0]));
  if (!f.startsWith(ROOT + path.sep) || !fs.existsSync(f) || !fs.statSync(f).isFile()) { res.writeHead(404); res.end(); return; }
  res.setHeader('Content-Type', types[path.extname(f)] || 'application/octet-stream'); res.end(fs.readFileSync(f));
});
(async () => {
  await new Promise(r => server.listen(PORT, '127.0.0.1', r));
  const browser = await chromium.launch({ headless: true, args: SOFT ? ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] : GPU ? ['--use-angle=metal', '--ignore-gpu-blocklist', '--enable-gpu-rasterization'] : [] });
  const ctx = await browser.newContext({ permissions: ['local-network-access'], viewport: { width: 1440, height: 1000 } });
  const page = await ctx.newPage(); const pageErrors = []; page.on('pageerror', e => pageErrors.push(e.message));
  const url = `https://project0.city/devkit?entry=${encodeURIComponent(`http://localhost:${PORT}/${ENTRY}`)}&width=25&depth=25&height=57&size=${SIZE}`;
  await page.goto(url, { waitUntil: 'domcontentloaded', timeout: 60000 });
  let status = await page.evaluate(() => devkit.wait()), attempts = 1;
  while (status !== 'started' && attempts < 4) {                 // the dev kit sometimes stalls while loading: try again
    attempts++; console.log('dev kit', status, '- restarting (attempt', attempts + ')');
    await page.goto(url, { waitUntil: 'domcontentloaded', timeout: 60000 });
    status = await page.evaluate(() => devkit.wait());
  }
  const res = { entry: ENTRY, size: SIZE, software: SOFT, status, attempts, pageErrors, shots: [] };
  const t0 = Date.now(), el = page.locator('#device');
  if (!opt('keep-panel', false)) await page.evaluate(() => { for (const b of document.querySelectorAll('*')) if (b.children.length === 0 && /^[×✕]$/.test((b.textContent || '').trim())) b.click(); });   // close the city's How-to-play panel
  if (status === 'started') {
    const events = [...SHOTS.map(t => ({ t, shot: true })), ...KEYS].sort((a, b) => a.t - b.t);
    for (const e of events) {
      const wait = e.t * 1000 - (Date.now() - t0); if (wait > 0) await page.waitForTimeout(wait);
      if (e.shot) { const f = `shot-${String(e.t).padStart(5, '0')}s.png`; try { await el.screenshot({ path: path.join(OUT, f) }); } catch (er) { await page.screenshot({ path: path.join(OUT, f) }); } res.shots.push(f); }
      else await page.evaluate(([c, ms]) => devkit.press(c, ms), [e.code, e.ms]);
    }
    const rest = UNTIL * 1000 - (Date.now() - t0); if (rest > 0) await page.waitForTimeout(rest);
  }
  res.final = await page.evaluate(() => ({ status: devkit.status, reason: devkit.reason, summary: devkit.summary(), errors: devkit.errors, frames: devkit.frames, console: devkit.console.slice(-40), hud: devkit.hud }));
  if (REVIEW && status === 'started') res.review = await page.evaluate(() => devkit.review(14));
  fs.writeFileSync(path.join(OUT, 'result.json'), JSON.stringify(res, null, 2));
  const f = res.final.frames || {};
  console.log(JSON.stringify({ status: res.final.status, reason: res.final.reason, errors: res.final.errors, pageErrors, fps: f.fps, p95: f.p95, worst: f.worst, first: f.first, shots: res.shots.length,
    review: res.review && { started: res.review.started, crash: res.review.crash, fps: res.review.fps, worst: res.review.worstFrame, errors: res.review.errors, blocked: res.review.blocked } }));
  for (const l of res.final.console) if (/error|SAVE LILLY/i.test(l)) console.log('  ', l.slice(0, 300));
  await browser.close(); server.close();
})().catch(e => { console.error(e); server.close(); process.exit(1); });
